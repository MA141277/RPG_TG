function uniqueIds(ids: string[]): string[] {
  return [...new Set(ids)];
}

function mergeCityRoster(
  baseRoster: HistoricalCityRoster,
  addition: HistoricalCityRoster
): HistoricalCityRoster {
  return {
    cityNodeId: baseRoster.cityNodeId,
    primaryCharacterIds: uniqueIds([
      ...baseRoster.primaryCharacterIds,
      ...addition.primaryCharacterIds,
    ]),
    secondaryCharacterIds: uniqueIds([
      ...baseRoster.secondaryCharacterIds,
      ...addition.secondaryCharacterIds,
    ]),
    backgroundCharacterIds: uniqueIds([
      ...baseRoster.backgroundCharacterIds,
      ...addition.backgroundCharacterIds,
    ]),
    notes: `${baseRoster.notes} ${addition.notes}`.trim(),
  };
}

export const zhuYuanzhangCityRosters: HistoricalCityRoster[] = [
  ...zhuYuanzhangCoreCityRosters,
];

for (const addition of zhuYuanzhangCityRosterAdditions) {
  const existingIndex = zhuYuanzhangCityRosters.findIndex(
    (roster) => roster.cityNodeId === addition.cityNodeId
  );
  if (existingIndex >= 0) {
    const existingRoster = zhuYuanzhangCityRosters[existingIndex];
    if (existingRoster != null) {
      zhuYuanzhangCityRosters[existingIndex] = mergeCityRoster(
        existingRoster,
        addition
      );
    }
  } else {
    zhuYuanzhangCityRosters.push(addition);
  }
}

export function selectHistoricalCharactersForCity(
  cityNodeId: string
): HistoricalCharacterRecord[] {
  return zhuYuanzhangEarlyCharacters.filter(
    (characterRecord) =>
      characterRecord.currentCityNodeId === cityNodeId ||
      characterRecord.homeCityNodeId === cityNodeId ||
      characterRecord.relatedCityNodeIds.includes(cityNodeId)
  );
}

export function selectCityNpcEligibleHistoricalCharacters(
  cityNodeId: string
): HistoricalCharacterRecord[] {
  return selectHistoricalCharactersForCity(cityNodeId).filter(
    (characterRecord) => characterRecord.cityNpcProfile?.enabled === true
  );
}

export function selectLeaderResidenceEligibleHistoricalCharacters(
  cityNodeId: string
): HistoricalCharacterRecord[] {
  return selectHistoricalCharactersForCity(cityNodeId).filter(
    (characterRecord) =>
      characterRecord.leaderResidenceProfile?.eligible === true
  );
}
