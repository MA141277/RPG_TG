function character(
  record: Omit<
    HistoricalCharacterRecord,
    | "displayName"
    | "aliases"
    | "birthYear"
    | "deathYear"
    | "activeYears"
    | "relatedCityNodeIds"
    | "sourceNotes"
    | "status"
  > &
    Partial<
      Pick<
        HistoricalCharacterRecord,
        | "displayName"
        | "aliases"
        | "birthYear"
        | "deathYear"
        | "activeYears"
        | "relatedCityNodeIds"
        | "sourceNotes"
        | "status"
        | "cityNpcProfile"
        | "leaderResidenceProfile"
      >
    >
): HistoricalCharacterRecord {
  return {
    displayName: record.canonicalName,
    aliases: [],
    birthYear: null,
    deathYear: null,
    activeYears: { from: null, to: null },
    relatedCityNodeIds: [],
    sourceNotes: [],
    status: "candidate",
    ...record,
  };
}

function leaderResidenceProfile(input: {
  role: NonNullable<HistoricalCharacterRecord["leaderResidenceProfile"]>["residenceRole"];
  title: string;
  occupation: string;
  affiliationLabel: string;
  teachableSkillKeys?: SkillKey[];
  status?: NonNullable<HistoricalCharacterRecord["leaderResidenceProfile"]>["status"];
}): NonNullable<HistoricalCharacterRecord["leaderResidenceProfile"]> {
  return {
    eligible: true,
    status: input.status ?? "available",
    residenceRole: input.role,
    title: input.title,
    occupation: input.occupation,
    affiliationLabel: input.affiliationLabel,
    teachableSkillKeys: input.teachableSkillKeys ?? [],
  };
}

function cityNpcProfile(input: {
  title: string;
  personality: string;
  specialty: string;
  activity?: Partial<Record<CityNpcActivityLocationId, number>>;
  dialogue?: string[];
  intel?: string[];
  favorability?: number;
}): NonNullable<HistoricalCharacterRecord["cityNpcProfile"]> {
  return {
    enabled: true,
    title: input.title,
    personality: input.personality,
    specialty: input.specialty,
    favorability: input.favorability ?? 0,
    activityWeight: input.activity ?? {
      "tea-house": 25,
      tavern: 15,
      market: 20,
      street: 40,
    },
    dialoguePool: input.dialogue ?? ["如今兵荒马乱，城中人人都在等一个准信。"],
    intelPool: input.intel ?? ["城中人物往来频繁，军府与市井消息常常互相牵连。"],
  };
}

function militaryResidence(title: string, affiliationLabel: string) {
  return leaderResidenceProfile({
    role: "general",
    title,
    occupation: "武将",
    affiliationLabel,
    teachableSkillKeys: ["military", "martial", "horse"],
  });
}

function advisorResidence(title: string, affiliationLabel: string) {
  return leaderResidenceProfile({
    role: "advisor",
    title,
    occupation: "谋士",
    affiliationLabel,
    teachableSkillKeys: ["military", "rhetoric", "arithmetic"],
  });
}

